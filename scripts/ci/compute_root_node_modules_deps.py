IMPORT_RE = re.compile(
    r"(?:import|export)\\s+(?:[^'\\\"]*?\\sfrom\\s+)?['\\\"]([^'\\\"]+)['\\\"]"
    r"|import\\(\\s*['\\\"]([^'\\\"]+)['\\\"]\\s*\\)"
    r"|require\\(\\s*['\\\"]([^'\\\"]+)['\\\"]\\s*\\)",
    re.MULTILINE,
)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Compute dynamic root node_modules dependency list")
    parser.add_argument("--modules-path", required=True, help="Path to modules root")
    parser.add_argument("--target-modules-json", default="[]", help="JSON array of target module names")
    parser.add_argument("--output", required=True, help="Output dependency file path")
    return parser.parse_args()


def load_package_json(path: pathlib.Path) -> dict:
    try:
        raw = path.read_text(encoding="utf-8")
    except OSError:
        return {}
    try:
        parsed = json.loads(raw)
    except json.JSONDecodeError:
        return {}
    return parsed if isinstance(parsed, dict) else {}


def list_modules(modules_root: pathlib.Path) -> list[str]:
    if not modules_root.is_dir():
        return []
    modules = []
    for child in modules_root.iterdir():
        if not child.is_dir():
            continue
        if child.name in IGNORED_MODULES:
            continue
        if not (child / "package.json").is_file():
            continue
        modules.append(child.name)
    return sorted(modules)


def build_manifest_index(modules_root: pathlib.Path, modules: list[str]) -> dict[str, dict]:
    manifests: dict[str, dict] = {}
    for module in modules:
        manifests[module] = load_package_json(modules_root / module / "package.json")
    return manifests


def parse_target_modules(raw: str, available_modules: set[str]) -> list[str]:
    try:
        parsed = json.loads(raw or "[]")
    except json.JSONDecodeError:
        parsed = []
    if not isinstance(parsed, list):
        parsed = []

    targets: list[str] = []
    seen: set[str] = set()
    for value in parsed:
        module = str(value).strip()
        if module == "" or module in seen:
            continue
        if module not in available_modules:
            continue
        seen.add(module)
        targets.append(module)
    return sorted(targets)


def expand_depends_closure(target_modules: list[str], manifests: dict[str, dict]) -> list[str]:
    if not target_modules:
        return sorted(manifests.keys())

    visited: set[str] = set()
    queue: deque[str] = deque(target_modules)

    while queue:
        module = queue.popleft().strip()
        if module == "" or module in visited:
            continue
        if module not in manifests:
            continue
        visited.add(module)

        manifest = manifests.get(module, {})
        choysum = manifest.get("choysum")
        depends = choysum.get("depends") if isinstance(choysum, dict) else []
        if not isinstance(depends, list):
            continue
        for dep in depends:
            dep_name = str(dep).strip()
            if dep_name != "" and dep_name in manifests and dep_name not in visited:
                queue.append(dep_name)

    return sorted(visited)


def normalize_package_name(specifier: str) -> str:
    specifier = specifier.strip()
    if specifier.startswith("@"):
        parts = specifier.split("/")
        if len(parts) >= 2:
            return f"{parts[0]}/{parts[1]}"
        return ""
    return specifier.split("/", 1)[0]


def should_skip_import_specifier(specifier: str) -> bool:
    value = specifier.strip()
    if value == "":
        return True
    if value.startswith(".") or value.startswith("/"):
        return True
    if value.startswith("node:"):
        return True
    if ":" in value:
        # URL-like or protocol specifier.
        return True
    package_name = normalize_package_name(value)
    if package_name == "" or package_name in NODE_BUILTINS:
        return True
    return False


def resolve_e2e_specs_dir(modules_root: pathlib.Path, module: str, manifest: dict) -> pathlib.Path | None:
    choysum = manifest.get("choysum")
    e2e = choysum.get("e2e") if isinstance(choysum, dict) else None
    specs_rel = e2e.get("specs") if isinstance(e2e, dict) else ""
    specs_rel = str(specs_rel).strip()
    if specs_rel == "":
        return None

    clean_rel = pathlib.PurePosixPath(specs_rel)
    if clean_rel.is_absolute():
        return None
    if clean_rel == pathlib.PurePosixPath("."):
        return None
    if any(part == ".." for part in clean_rel.parts):
        return None

    specs_dir = modules_root / module / pathlib.Path(*clean_rel.parts)
    if specs_dir.is_dir():
        return specs_dir
    return None


def collect_e2e_spec_imports(modules_root: pathlib.Path, closure_modules: list[str], manifests: dict[str, dict]) -> set[str]:
    found: set[str] = set()
    extensions = {".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs"}

    for module in closure_modules:
        manifest = manifests.get(module, {})
        specs_dir = resolve_e2e_specs_dir(modules_root, module, manifest)
        if specs_dir is None:
            continue

        for path in specs_dir.rglob("*"):
            if not path.is_file() or path.suffix not in extensions:
                continue
            try:
                content = path.read_text(encoding="utf-8")
            except (OSError, UnicodeDecodeError):
                continue

            for match in IMPORT_RE.finditer(content):
                specifier = next((group for group in match.groups() if group), "")
                if should_skip_import_specifier(specifier):
                    continue
                found.add(normalize_package_name(specifier))

    return found


def sanitize_version_spec(version_spec: str) -> str:
    version_spec = version_spec.strip()
    if version_spec == "":
        return ""
    if any(ch.isspace() for ch in version_spec):
        return ""
    if version_spec.startswith(("workspace:", "file:", "link:")):
        return ""
    return version_spec


def add_dependency(dep_specs: dict[str, str], package: str, version_spec: str, source: str) -> None:
    package = package.strip()
    if package == "" or package.startswith("@choysum-dev/"):
        return

    normalized_spec = sanitize_version_spec(version_spec)
    current = dep_specs.get(package)
    if current is None:
        dep_specs[package] = normalized_spec
        return

    if current == normalized_spec or normalized_spec == "":
        return
    if current == "":
        dep_specs[package] = normalized_spec
        return

    # Keep deterministic behavior; prefer the first non-empty range and log.
    print(
        f"compute-root-node-modules-deps: version conflict for {package}: kept {current!r}, ignored {normalized_spec!r} from {source}",
        file=sys.stderr,
    )


def collect_dynamic_dependencies(modules_root: pathlib.Path, closure_modules: list[str], manifests: dict[str, dict]) -> dict[str, str]:
    dep_specs: dict[str, str] = {}

    for module in closure_modules:
        manifest = manifests.get(module, {})
        for field in ("dependencies", "peerDependencies"):
            deps = manifest.get(field)
            if not isinstance(deps, dict):
                continue
            for package, version_spec in sorted(deps.items()):
                add_dependency(dep_specs, str(package), str(version_spec), f"{module}:{field}")

    for package in sorted(collect_e2e_spec_imports(modules_root, closure_modules, manifests)):
        add_dependency(dep_specs, package, "", "e2e-spec-import")

    for package, version_spec in sorted(BASE_TOOLCHAIN_DEPENDENCIES.items()):
        add_dependency(dep_specs, package, version_spec, "base")

    return dep_specs


def format_dependency_spec(package: str, version_spec: str) -> str:
    if version_spec == "":
        return package
    return f"{package}@{version_spec}"


def main() -> int:
    args = parse_args()
    modules_root = pathlib.Path(args.modules_path).resolve()
    output_path = pathlib.Path(args.output).resolve()

    modules = list_modules(modules_root)
    module_set = set(modules)
    manifests = build_manifest_index(modules_root, modules)
    requested_targets = parse_target_modules(args.target_modules_json, module_set)
    closure_modules = expand_depends_closure(requested_targets, manifests)

    dep_specs = collect_dynamic_dependencies(modules_root, closure_modules, manifests)
    lines = [format_dependency_spec(package, dep_specs[package]) for package in sorted(dep_specs)]

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text("\n".join(lines) + "\n", encoding="utf-8")

    print(
        f"compute-root-node-modules-deps: modules={len(closure_modules)} deps={len(lines)} output={output_path}",
        file=sys.stderr,
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())