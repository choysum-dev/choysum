from __future__ import annotations

import argparse
import importlib.util
import json
import pathlib
import shutil
import subprocess
import sys


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Install root node_modules from compute_root_node_modules_deps.py output",
    )
    parser.add_argument("--deps-file", required=True, help="Dependency list file path")
    parser.add_argument(
        "--workspace",
        default=".",
        help="Workspace directory that should receive node_modules",
    )
    return parser.parse_args()


def parse_dep_spec(line: str) -> tuple[str, str] | None:
    line = line.strip()
    if line == "" or line.startswith("#"):
        return None

    if line.startswith("@"):
        version_at = line.rfind("@")
        if version_at <= 0:
            return None
        if version_at == line.index("@"):
            return line, "latest"
        return line[:version_at], line[version_at + 1 :]

    if "@" in line:
        package, version = line.rsplit("@", 1)
        if package == "":
            return None
        return package, version

    return line, "latest"


def load_dependencies(deps_file: pathlib.Path) -> tuple[list[str], dict[str, str]]:
    lines: list[str] = []
    dependencies: dict[str, str] = {}
    for raw in deps_file.read_text(encoding="utf-8").splitlines():
        parsed = parse_dep_spec(raw)
        if parsed is None:
            continue
        package, version = parsed
        lines.append(raw.strip())
        dependencies[package] = version
    return lines, dependencies


def load_peer_completion() -> dict[str, tuple[str, str]]:
    script = pathlib.Path(__file__).with_name("compute_root_node_modules_deps.py")
    spec = importlib.util.spec_from_file_location("_compute_root_node_modules_deps", script)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"Unable to load peer completion from {script}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    peer_completion = getattr(module, "PEER_COMPLETION", None)
    if not isinstance(peer_completion, dict):
        raise RuntimeError(f"{script} is missing PEER_COMPLETION")
    return peer_completion


def npm_cmd(*args: str, legacy_peer_deps: bool = False) -> list[str]:
    cmd = ["npm", *args, "--no-fund", "--no-audit"]
    if legacy_peer_deps:
        cmd.append("--legacy-peer-deps")
    return cmd


def package_node_modules_path(install_root: pathlib.Path, package: str) -> pathlib.Path:
    if package.startswith("@"):
        scope, name = package.split("/", 1)
        return install_root / "node_modules" / scope / name
    return install_root / "node_modules" / package


def write_manifest(install_root: pathlib.Path, dependencies: dict[str, str]) -> None:
    install_root.mkdir(parents=True, exist_ok=True)
    manifest = {
        "name": "choysum-root-test-toolchain",
        "private": True,
        "dependencies": dependencies,
    }
    (install_root / "package.json").write_text(
        json.dumps(manifest, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )


def ensure_peer_packages(install_root: pathlib.Path, dependencies: dict[str, str]) -> None:
    for parent, (peer, version) in load_peer_completion().items():
        if parent not in dependencies:
            continue
        if package_node_modules_path(install_root, peer).is_dir():
            continue
        spec = peer if version == "" else f"{peer}@{version}"
        subprocess.run(
            npm_cmd(
                "install",
                "--include=dev",
                "--no-package-lock",
                "--no-save",
                spec,
                legacy_peer_deps=True,
            ),
            cwd=install_root,
            check=True,
        )


def install_with_manifest(
    install_root: pathlib.Path,
    dependencies: dict[str, str],
    *,
    legacy_peer_deps: bool,
) -> None:
    write_manifest(install_root, dependencies)
    subprocess.run(
        npm_cmd(
            "install",
            "--include=dev",
            "--no-package-lock",
            legacy_peer_deps=legacy_peer_deps,
        ),
        cwd=install_root,
        check=True,
    )


def install_sequential(
    install_root: pathlib.Path,
    dep_lines: list[str],
    *,
    legacy_peer_deps: bool,
) -> None:
    write_manifest(install_root, {})
    for dep in dep_lines:
        subprocess.run(
            npm_cmd(
                "install",
                "--include=dev",
                "--no-package-lock",
                "--no-save",
                dep,
                legacy_peer_deps=legacy_peer_deps,
            ),
            cwd=install_root,
            check=True,
        )


def publish_node_modules(install_root: pathlib.Path, workspace: pathlib.Path) -> None:
    source = install_root / "node_modules"
    if not source.is_dir():
        raise SystemExit(f"Expected node_modules at {source}")

    target = workspace / "node_modules"
    if target.exists():
        shutil.rmtree(target)
    shutil.move(str(source), str(target))


def verify_required_packages(workspace: pathlib.Path, dependencies: dict[str, str]) -> None:
    install_root = workspace
    for parent, (peer, _version) in load_peer_completion().items():
        if parent not in dependencies:
            continue
        if not package_node_modules_path(install_root, peer).is_dir():
            raise SystemExit(f"Missing {peer} after root node_modules install")


def main() -> int:
    args = parse_args()
    deps_file = pathlib.Path(args.deps_file).resolve()
    workspace = pathlib.Path(args.workspace).resolve()
    if not deps_file.is_file():
        print(f"Error: deps file {deps_file} does not exist", file=sys.stderr)
        return 1
    if not workspace.is_dir():
        print(f"Error: workspace {workspace} is not a directory", file=sys.stderr)
        return 1

    dep_lines, dependencies = load_dependencies(deps_file)
    if not dependencies:
        print("Error: dependency list is empty", file=sys.stderr)
        return 1

    install_root = workspace / ".choysum" / "tmp" / "root-nm-install"
    if install_root.exists():
        shutil.rmtree(install_root)

    install_mode = "manifest"
    try:
        install_with_manifest(install_root, dependencies, legacy_peer_deps=False)
    except subprocess.CalledProcessError:
        print(
            "install-root-node-modules: strict manifest install failed; retrying with legacy peer deps",
            file=sys.stderr,
        )
        if install_root.exists():
            shutil.rmtree(install_root, ignore_errors=True)
        try:
            install_with_manifest(install_root, dependencies, legacy_peer_deps=True)
            ensure_peer_packages(install_root, dependencies)
        except subprocess.CalledProcessError:
            print(
                "install-root-node-modules: legacy manifest install failed; retrying sequentially",
                file=sys.stderr,
            )
            if install_root.exists():
                shutil.rmtree(install_root, ignore_errors=True)
            install_sequential(install_root, dep_lines, legacy_peer_deps=True)
            ensure_peer_packages(install_root, dependencies)
            install_mode = "sequential"

    publish_node_modules(install_root, workspace)
    verify_required_packages(workspace, dependencies)
    shutil.rmtree(install_root, ignore_errors=True)
    print(
        f"install-root-node-modules: installed {len(dep_lines)} dependencies via {install_mode}",
        file=sys.stderr,
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
