func TestTailwindInputDigestStableAndSensitive(t *testing.T) {
	root := t.TempDir()
	modules := filepath.Join(root, "modules")
	web := filepath.Join(modules, "web", "web")
	styles := filepath.Join(web, "styles")
	pages := filepath.Join(web, "pages")
	if err := os.MkdirAll(styles, 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.MkdirAll(pages, 0o755); err != nil {
		t.Fatal(err)
	}
	dialect := `@theme { --color-primary: blue; }`
	if err := os.WriteFile(filepath.Join(styles, "theme.css"), []byte(dialect), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(pages, "Gallery.vue"), []byte(`<div class="flex p-4"></div>`), 0o644); err != nil {
		t.Fatal(err)
	}

	d1, c1, err := TailwindInputDigest(modules)
	if err != nil {
		t.Fatal(err)
	}
	if d1 == "" || c1 == "" {
		t.Fatalf("expected hashes, got dialect=%q content=%q", d1, c1)
	}
	d2, c2, err := TailwindInputDigest(modules)
	if err != nil {
		t.Fatal(err)
	}
	if d1 != d2 || c1 != c2 {
		t.Fatalf("unstable digest: %s/%s vs %s/%s", d1, c1, d2, c2)
	}

	if err := os.WriteFile(filepath.Join(styles, "theme.css"), []byte(`@theme { --color-primary: red; }`), 0o644); err != nil {
		t.Fatal(err)
	}
	d3, c3, err := TailwindInputDigest(modules)
	if err != nil {
		t.Fatal(err)
	}
	if d3 == d1 {
		t.Fatal("dialect change should alter dialect hash")
	}
	if c3 != c1 {
		t.Fatal("dialect-only change should keep content hash")
	}

	if err := os.WriteFile(filepath.Join(pages, "Gallery.vue"), []byte(`<div class="flex p-4 gap-2"></div>`), 0o644); err != nil {
		t.Fatal(err)
	}
	_, c4, err := TailwindInputDigest(modules)
	if err != nil {
		t.Fatal(err)
	}
	if c4 == c3 {
		t.Fatal("candidate change should alter content hash")
	}

	emptyD, emptyC, err := TailwindInputDigest(t.TempDir())
	if err != nil {
		t.Fatal(err)
	}
	if emptyD != "" || emptyC != "" {
		t.Fatalf("missing kit should return empty hashes, got %q %q", emptyD, emptyC)
	}

	// web as a file → no-op (aligned with EnsureChoyTailwindCSS).
	fileRoot := t.TempDir()
	webFile := filepath.Join(fileRoot, "web", "web")
	if err := os.MkdirAll(filepath.Dir(webFile), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(webFile, []byte("not a dir"), 0o644); err != nil {
		t.Fatal(err)
	}
	d, c, err := TailwindInputDigest(fileRoot)
	if err != nil || d != "" || c != "" {
		t.Fatalf("web file => empty hashes, got %q %q %v", d, c, err)
	}

	// dialect path is a directory → broken kit (same as EnsureChoyTailwindCSS).
	dirRoot := t.TempDir()
	stylesDir := filepath.Join(dirRoot, "web", "web", "styles")
	if err := os.MkdirAll(stylesDir, 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.Mkdir(filepath.Join(stylesDir, "theme.css"), 0o755); err != nil {
		t.Fatal(err)
	}
	d, c, err = TailwindInputDigest(dirRoot)
	if err == nil || !strings.Contains(err.Error(), "directory") || d != "" || c != "" {
		t.Fatalf("directory dialect => error, got %q %q %v", d, c, err)
	}
}

