func TestGenerateTailwindCSSNonEmptyAndWithinBudget(t *testing.T) {
	dialect := `@theme { --color-primary: var(--choy-color-primary); }`
	candidates := []string{"flex", "items-center", "p-4", "bg-primary", "text-sm", "rounded-md", "border", "gap-4"}
	css, dur, err := GenerateTailwindCSS(dialect, candidates)
	if err != nil {
		t.Fatalf("GenerateTailwindCSS: %v", err)
	}
	if strings.TrimSpace(css) == "" {
		t.Fatal("expected non-empty CSS")
	}
	if !strings.Contains(css, "display: flex") {
		t.Fatalf("expected flex utility in CSS, got:\n%s", css)
	}
	if !strings.Contains(css, "var(--color-primary)") {
		t.Fatalf("expected theme-mapped utility var(--color-primary), got:\n%s", css)
	}
	if !strings.Contains(css, "--color-primary:") {
		t.Fatalf("expected ThemeCSS alias --color-primary:, got:\n%s", css)
	}
	if !strings.Contains(css, ".flex") {
		t.Fatalf("expected unscoped .flex utility for main bundle, got:\n%s", css)
	}
	if strings.Contains(css, choyGalleryRootSelector+" .flex") {
		t.Fatalf("cutover CSS must not gallery-scope utilities, got:\n%s", css)
	}
	if strings.Contains(css, "*, ::before") {
		t.Fatalf("generated CSS must not include Tailwind preflight:\n%s", css)
	}
	if dur > ChoyTailwindBudget {
		t.Fatalf("generate duration %v exceeds budget %v", dur, ChoyTailwindBudget)
	}
	t.Logf("GenerateTailwindCSS duration=%v len=%d (budget=%v)", dur, len(css), ChoyTailwindBudget)
}

func TestGenerateChoyTailwindForModuleWritesFile(t *testing.T) {
	root := t.TempDir()
	web := filepath.Join(root, "web")
	styles := filepath.Join(web, "styles")
	pages := filepath.Join(web, "pages")
	if err := os.MkdirAll(styles, 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.MkdirAll(pages, 0o755); err != nil {
		t.Fatal(err)
	}
	dialect := `@theme { --color-primary: var(--choy-color-primary); --color-muted: var(--choy-color-muted); }`
	if err := os.WriteFile(filepath.Join(styles, "theme.css"), []byte(dialect), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(pages, "Gallery.vue"), []byte(`<div class="flex p-4 bg-primary bg-muted"></div>`), 0o644); err != nil {
		t.Fatal(err)
	}

	res, err := GenerateChoyTailwindForModule(root)
	if err != nil {
		t.Fatalf("GenerateChoyTailwindForModule: %v", err)
	}
	if res == nil {
		t.Fatal("expected result")
	}
	if res.CandidateCount < 1 {
		t.Fatalf("expected candidates, got %d", res.CandidateCount)
	}
	if res.Duration > ChoyTailwindBudget {
		t.Fatalf("module generate %v exceeds budget %v", res.Duration, ChoyTailwindBudget)
	}
	data, err := os.ReadFile(res.OutputPath)
	if err != nil {
		t.Fatal(err)
	}
	body := string(data)
	if !strings.Contains(body, "Generated by choysum") {
		t.Fatalf("missing header in %s", res.OutputPath)
	}
	if !strings.Contains(body, "engine=") {
		t.Fatalf("header must record engine version:\n%s", body)
	}
	if strings.Contains(body, "*, ::before") {
		t.Fatalf("generated CSS contains Tailwind preflight:\n%s", body)
	}
	if !strings.Contains(body, "--color-primary:") {
		t.Fatalf("expected ThemeCSS --color-primary alias:\n%s", body)
	}
	if !strings.Contains(body, ".flex") {
		t.Fatalf("expected unscoped .flex utility:\n%s", body)
	}
	if strings.Contains(body, choyGalleryRootSelector+" .flex") {
		t.Fatalf("cutover CSS must not gallery-scope utilities:\n%s", body)
	}
	if !strings.Contains(body, "Cutover:") {
		t.Fatalf("header must record cutover product mode:\n%s", body)
	}
	if res.DialectHash == "" || res.ContentHash == "" {
		t.Fatal("expected dialect and content hashes")
	}

	// Stability: same inputs → same content hash.
	res2, err := GenerateChoyTailwindForModule(root)
	if err != nil {
		t.Fatal(err)
	}
	if res.ContentHash != res2.ContentHash || res.DialectHash != res2.DialectHash {
		t.Fatalf("hashes unstable: %#v vs %#v", res, res2)
	}
}

