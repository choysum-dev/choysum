package lifecycle

import (
	"fmt"
	"os"
	"path/filepath"
	"strconv"
	"strings"
	"unicode"

	"github.com/choysum-dev/choysum/internal/module/evolution/hooks"
	"github.com/choysum-dev/choysum/pkg/meta"
)

func writeFileString(path, content string) error {
	return os.WriteFile(path, []byte(content), 0o644)
}

// seededModuleImport describes one backend module import with CHOYSUM_* seed.
type seededModuleImport struct {
	AppName    string
	ModuleName string
	EntryPath  string // absolute cleaned service entry path
	SeedFile   string // basename under entryDir, e.g. __seed_mod_document.ts
}

func sanitizeSeedFileToken(name string) string {
	var b strings.Builder
	for _, r := range strings.TrimSpace(name) {
		switch {
		case unicode.IsLetter(r), unicode.IsDigit(r):
			b.WriteRune(r)
		case r == '_' || r == '-':
			b.WriteRune(r)
		default:
			b.WriteByte('_')
		}
	}
	out := b.String()
	if out == "" {
		return "mod"
	}
	return out
}

func buildSeededModuleImports(mods []*meta.Module, modulesPath string) []seededModuleImport {
	out := make([]seededModuleImport, 0, len(mods))
	seenSeed := map[string]int{}
	for _, mod := range mods {
		if mod == nil {
			continue
		}
		entry := strings.TrimSpace(mod.ServiceEntryPoint)
		if entry == "" {
			continue
		}
		if !filepath.IsAbs(entry) {
			entry = filepath.Join(modulesPath, mod.Name, entry)
		}
		entry = filepath.Clean(entry)
		appName := strings.TrimSpace(mod.ApplicationStr)
		moduleName := strings.TrimSpace(mod.Name)
		if appName == "" {
			appName = moduleName
		}
		token := sanitizeSeedFileToken(moduleName)
		n := seenSeed[token]
		seenSeed[token] = n + 1
		if n > 0 {
			token = fmt.Sprintf("%s_%d", token, n+1)
		}
		out = append(out, seededModuleImport{
			AppName:    appName,
			ModuleName: moduleName,
			EntryPath:  entry,
			SeedFile:   "__seed_mod_" + token + ".ts",
		})
	}
	return out
}

func seedModuleFileContent(appName, moduleName string) string {
	var b strings.Builder
	b.WriteString("// Generated by Choysum. DO NOT EDIT.\n")
	b.WriteString("// Sets CHOYSUM_* before the paired service entry import in the parent entry.\n")
	b.WriteString("globalThis.CHOYSUM_APP_NAME = ")
	b.WriteString(strconv.Quote(appName))
	b.WriteString(";\n")
	b.WriteString("globalThis.CHOYSUM_MODULE_NAME = ")
	b.WriteString(strconv.Quote(moduleName))
	b.WriteString(";\n")
	b.WriteString("export {};\n")
	return b.String()
}

func hookDispatcherFileContent() string {
	return "// Generated by Choysum. DO NOT EDIT.\n" + hooks.HookDispatcherScriptContent + "\nexport {};\n"
}

// writeSeededBundlesEntry writes the multi-app (or multi-module) synthetic entry:
// hook dispatcher, then for each module (seed file import, service entry import).
// Seed modules have no imports so they evaluate before the following service entry
// in ESM dependency order, registering @Hook* under the correct CHOYSUM_* identity.
func writeSeededBundlesEntry(entryDir, entryFileName string, imports []seededModuleImport) (entryFilePath string, err error) {
	dispatcherName := "__choysum_hook_dispatcher.ts"
	if err := writeFileString(filepath.Join(entryDir, dispatcherName), hookDispatcherFileContent()); err != nil {
		return "", err
	}
	for _, item := range imports {
		if err := writeFileString(filepath.Join(entryDir, item.SeedFile), seedModuleFileContent(item.AppName, item.ModuleName)); err != nil {
			return "", err
		}
	}

	var b strings.Builder
	b.WriteString("// Generated by Choysum. DO NOT EDIT.\n")
	b.WriteString(`import "./`)
	b.WriteString(dispatcherName)
	b.WriteString(`";` + "\n")
	if len(imports) == 0 {
		b.WriteString("export {};\n")
	} else {
		for _, item := range imports {
			b.WriteString(`import "./`)
			b.WriteString(item.SeedFile)
			b.WriteString(`";` + "\n")
			b.WriteString(`import "`)
			b.WriteString(item.EntryPath)
			b.WriteString(`";` + "\n")
		}
	}
	entryFilePath = filepath.Join(entryDir, entryFileName)
	if err := writeFileString(entryFilePath, b.String()); err != nil {
		return "", err
	}
	return entryFilePath, nil
}
