func (m *ModuleManager) ensureMetaTables() error {
	var migrateErr error
	m.bootstrapOnce.Do(func() {
		// Bootstrap meta tables in an isolated transaction that is committed
		// independently from any caller transaction.
		// This avoids visibility issues when the caller is already inside an open
		// transaction and another operation uses its own lease/meta transaction.
		txRoot := m.runtimeScope.WithContext(m.runtimeScope.Context())
		migrateErr = txRoot.Transactor().RequiresNew(txRoot.Context(), func(txScope scope.Scope, _ scope.Transaction) error {
			migrator := txScope.Session().Migrator()

			if migrator.HasTable(&meta.IrModule{}) && migrator.HasTable(&leasemodel.IrLockLease{}) {
				return nil
			}

			logger := txScope.Logger()
			startedAt := time.Now()
			if logger != nil {
				logger.Info("meta base table bootstrap started", "entity_count", len(m.entities))
			}

			const (
				metaBootstrapHeartbeatThreshold = 5 * time.Second
				metaBootstrapHeartbeatInterval  = 5 * time.Second
			)
			stopHeartbeat := func() {}
			if logger != nil {
				stopCh := make(chan struct{})
				doneCh := make(chan struct{})
				go func() {
					defer close(doneCh)
					ticker := time.NewTicker(metaBootstrapHeartbeatInterval)
					defer ticker.Stop()
					lastHeartbeatAt := startedAt
					for {
						select {
						case <-stopCh:
							return
						case now := <-ticker.C:
							elapsed := now.Sub(startedAt)
							if elapsed >= metaBootstrapHeartbeatThreshold && now.Sub(lastHeartbeatAt) >= metaBootstrapHeartbeatInterval {
								logger.Info("meta base table bootstrap heartbeat", "elapsed_ms", elapsed.Milliseconds())
								lastHeartbeatAt = now
							}
						}
					}
				}()
				stopHeartbeat = func() {
					close(stopCh)
					<-doneCh
				}
			}
			defer stopHeartbeat()

			if err := txScope.Session().AutoMigrate(m.entities...); err != nil {
				return xfmt.Errorf("auto migrate meta entities: %w", err)
			}
			if logger != nil {
				logger.Info("meta base table bootstrap completed", "duration_ms", time.Since(startedAt).Milliseconds())
			}
			return nil
		})
	})
	return migrateErr
}

func (m *ModuleManager) withModuleManagerLease(ctx context.Context, fn func() error) error {
	if err := m.ensureMetaTables(); err != nil {
		return err
	}
	if ctx == nil {
		ctx = context.Background()
	}

	locker := m.lockerFactory(m.runtimeScope)
	resource := "module_management"
	ownerId := xid.New().String()
	ttl := 60 * time.Second

	if err := locker.Acquire(ctx, resource, ownerId, ttl); err != nil {
		if errors.Is(err, lease.ErrLeaseBusy) {
			retryAfterMs := int64(ttl / time.Millisecond)
			return oerrors.New("meta.lock", "LEASE_CONFLICT", "lease is busy").WithMetadata("retry_after_ms", fmt.Sprintf("%d", retryAfterMs))
		}
		return err
	}

	heartbeatCtx, cancel := context.WithCancel(ctx)
	defer cancel()

	done := make(chan struct{})
	go func() {
		defer close(done)
		ticker := time.NewTicker(ttl / 2)
		defer ticker.Stop()
		for {
			select {
			case <-heartbeatCtx.Done():
				return
			case <-ticker.C:
				if err := locker.Renew(heartbeatCtx, resource, ownerId, ttl); err != nil {
					m.runtimeScope.Logger().Warn("module manager lease renew failed", "resource", resource, "error", err)
				}
			}
		}
	}()

	defer func() {
		cancel()
		<-done
		releaseLeaseWithContextFallback(m.runtimeScope, locker, ctx, resource, ownerId, "module manager")
	}()

	return fn()
}

// releaseLeaseWithContextFallback tries to release a lease using the current
// operation context first (which can reuse an active sqlite transaction/session),
// then falls back to a fresh background context when needed.
func releaseLeaseWithContextFallback(runtimeScope scope.Scope, locker statepkg.Locker, operationCtx context.Context, resource, ownerID, label string) {
	if locker == nil {
		return
	}

	if operationCtx != nil && operationCtx.Err() == nil {
		primaryErr := func() error {
			primaryCtx, primaryCancel := context.WithTimeout(operationCtx, 2*time.Second)
			defer primaryCancel()
			return locker.Release(primaryCtx, resource, ownerID)
		}()

		if primaryErr == nil {
			return
		} else if errors.Is(primaryErr, statepkg.ErrLeaseNotOwner) || errors.Is(primaryErr, statepkg.ErrLeaseNotHeld) {
			if runtimeScope != nil {
				runtimeScope.Logger().Warn(label+" lease release failed", "resource", resource, "error", primaryErr)
			}
			return
		} else if runtimeScope != nil {
			runtimeScope.Logger().Debug(label+" lease release retry with background context", "resource", resource, "error", primaryErr)
		}
	}

	releaseCtx, releaseCancel := context.WithTimeout(context.Background(), 30*time.Second)
	defer releaseCancel()
	if err := locker.Release(releaseCtx, resource, ownerID); err != nil && !errors.Is(err, statepkg.ErrLeaseNotOwner) && !errors.Is(err, statepkg.ErrLeaseNotHeld) {
		if runtimeScope != nil {
			runtimeScope.Logger().Warn(label+" lease release failed", "resource", resource, "error", err)
		}
	}
}

func (m *ModuleManager) migrateBaseModule() error {
	m.runtimeScope.Logger().Debug("base module entity migration started")
	if err := m.runtimeScope.Session().AutoMigrate(
		m.entities...,
	); err != nil {
		return xfmt.Errorf("error migrating base module: %w", err)
	}
	return nil
}

func (m *ModuleManager) resolveInstallModuleFromOrigin(ctx context.Context, name string) (*meta.IrModule, error) {
	if err := m.ensureMetaTables(); err != nil {
		return nil, err
	}
	if ctx == nil {
		ctx = context.Background()
	}
	name = strings.TrimSpace(name)
	if name == "" {
		return nil, xfmt.Errorf("module name is empty")
	}

	coordinator := m.newOriginCoordinator()
	module, err := coordinator.ResolveInstallModule(ctx, name)
	if err != nil {
		return nil, xfmt.Errorf("error resolving module %s from origin: %w", name, err)
	}

	if meta.IsCoreModule(module.Name) {
		if err := m.migrateBaseModule(); err != nil {
			return nil, err
		}
	}

	return module, nil
}

func (m *ModuleManager) Peek(ctx context.Context, name string) (*meta.IrModule, error) {
	if err := m.ensureMetaTables(); err != nil {
		return nil, err
	}
	if ctx == nil {
		ctx = context.Background()
	}
	coordinator := m.newOriginCoordinator()
	module, err := coordinator.Peek(ctx, name)
	if err != nil {
		return nil, xfmt.Errorf("error peeking module %s: %w", name, err)
	}
	return module, nil
}

func (m *ModuleManager) Load(name string) (*meta.IrModule, error) {
	if err := m.ensureMetaTables(); err != nil {
		return nil, err
	}

	if meta.IsCoreModule(name) {
		if err := m.migrateBaseModule(); err != nil {
			return nil, err
		}
	}

	var module meta.IrModule
	if result := m.runtimeScope.Session().
		Preload("Dependencies", func(db *gorm.DB) *gorm.DB { return db.Where("status = ?", meta.Installed).Order("id ASC") }).
		Preload("Dependents", func(db *gorm.DB) *gorm.DB { return db.Where("status = ?", meta.Installed).Order("id ASC") }).
		Where("name = ?", name).Take(&module); result.Error != nil {
		if !errors.Is(result.Error, gorm.ErrRecordNotFound) {
			return nil, xfmt.Errorf("error loading module %s: %w", name, result.Error)
		} else {
			return nil, nil
		}
	}
	return &module, nil
}

func ensureOpIDInContext(ctx context.Context) (context.Context, string) {
	if ctx == nil {
		ctx = context.Background()
	}
	if opid, ok := staging.OpIDFromContext(ctx); ok {
		return ctx, opid
	}
	opid := staging.NewOpID()
	return staging.WithOpID(ctx, opid), opid
}

func moduleOpLogger(logger *slog.Logger, opid string, op plan.OpType, moduleName string) *slog.Logger {
	if logger == nil {
		logger = slog.Default()
	}
	attrs := []any{"opid", opid, "op", string(op), "module", moduleName}
	return logger.With(attrs...)
}

