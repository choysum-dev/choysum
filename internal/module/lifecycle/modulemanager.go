func (m *ModuleManager) generateAppToDirs(ctx context.Context, appName string, modulesTargets pipeline.ModulesAppTargets, distAppDir string) error {
	select {
	case <-ctx.Done():
		return ctx.Err()
	default:
	}

	if err := m.ensureMetaTables(); err != nil {
		return err
	}

	var mod meta.IrModule
	result := m.runtimeScope.Session().
		Where("application_str = ? AND status = ?", appName, meta.Installed).
		Order("name ASC").
		Take(&mod)
	if result.Error != nil {
		if errors.Is(result.Error, gorm.ErrRecordNotFound) {
			return nil
		}
		return xfmt.Errorf("error loading module for app %s: %w", appName, result.Error)
	}

	gen := modulegenerator.NewGrpcGenerator(m.runtimeScope, &mod)
	genToTargets, ok := gen.(module.GeneratorToTargets)
	if !ok {
		return xfmt.Errorf("generator does not support GenerateToTargetsCtx")
	}
	if _, err := genToTargets.GenerateToTargetsCtx(ctx, modulesTargets.ProtoDir, modulesTargets.WebDir, modulesTargets.ServiceDir, distAppDir); err != nil {
		return xfmt.Errorf("error generating app %s: %w", appName, err)
	}
	return nil
}

func (m *ModuleManager) buildBackendAppToDir(ctx context.Context, appName string, distAppDir string) error {
	select {
	case <-ctx.Done():
		return ctx.Err()
	default:
	}

	if err := m.ensureMetaTables(); err != nil {
		return err
	}

	var mods []meta.IrModule
	if err := m.runtimeScope.Session().
		Where("application_str = ? AND status = ? AND service_entry_point <> ''", appName, meta.Installed).
		Order("id ASC").
		Find(&mods).Error; err != nil {
		return xfmt.Errorf("error loading backend modules for app %s: %w", appName, err)
	}
	if len(mods) == 0 {
		return nil
	}
	runtimeOpts := m.resolvedRuntimeOptions()

	if err := os.MkdirAll(distAppDir, 0o755); err != nil {
		return xfmt.Errorf("create staging app dir %s: %w", distAppDir, err)
	}
	entryFilePath := filepath.Join(distAppDir, "__choysum_app_entry.ts")
	var b strings.Builder
	b.WriteString("// Generated by Choysum. DO NOT EDIT.\n")
	for i := range mods {
		entry := strings.TrimSpace(mods[i].ServiceEntryPoint)
		if entry == "" {
			continue
		}
		if !filepath.IsAbs(entry) {
			entry = filepath.Join(runtimeOpts.modulesPath, mods[i].Name, entry)
		}
		entry = filepath.Clean(entry)
		b.WriteString("import \"")
		b.WriteString(entry)
		b.WriteString("\";\n")
	}
	if err := os.WriteFile(entryFilePath, []byte(b.String()), 0o644); err != nil {
		return xfmt.Errorf("write app entry: %w", err)
	}

	// Use the last installed module as representative for build metadata.
	rep := &mods[len(mods)-1]
	builder := internalbackendbuilder.NewModuleBuilder(m.runtimeScope, m.jsExecutor, rep, entryFilePath, internalbackendbuilder.WithPublishDist(true))
	bundlerToDir, ok := builder.(module.BundlerToDir)
	if !ok {
		return xfmt.Errorf("backend builder does not support BundleToDirCtx")
	}
	if _, err := bundlerToDir.BundleToDirCtx(ctx, distAppDir); err != nil {
		return xfmt.Errorf("backend bundle failed for app %s: %w", appName, err)
	}
	return nil
}

func (m *ModuleManager) buildGlobalWebToDir(ctx context.Context, distWebDir string) error {
	select {
	case <-ctx.Done():
		return ctx.Err()
	default:
	}

	webMod, err := m.Load("web")
	if err != nil {
		return err
	}

	if webMod == nil || webMod.Status != meta.Installed || webMod.WebEntryPoint == "" {
		// No web module: leave staging empty; pipeline commit will replace dist/web.
		return nil
	}

	entry := webMod.WebEntryPoint
	runtimeOpts := m.resolvedRuntimeOptions()
	if !filepath.IsAbs(entry) {
		entry = filepath.Join(runtimeOpts.modulesPath, webMod.Name, entry)
	}
	webMod.WebEntryPoint = entry

	b := internalwebmodulebuilder.NewWebBuilder(m.runtimeScope, m.jsExecutor, webMod, entry)
	bToDir, ok := b.(module.BuilderToDir)
	if !ok {
		return xfmt.Errorf("web builder does not support BuildToDirCtx")
	}
	if _, err := bToDir.BuildToDirCtx(ctx, distWebDir); err != nil {
		return xfmt.Errorf("global web build failed: %w", err)
	}
	return nil
}

