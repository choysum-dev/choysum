func TestReadGoModulePathAndFilterHandwrittenGoCoverProfile(t *testing.T) {
	repoRoot := t.TempDir()
	if err := os.WriteFile(filepath.Join(repoRoot, "go.mod"), []byte("module example.com/project\n"), 0o644); err != nil {
		t.Fatalf("WriteFile go.mod: %v", err)
	}
	if err := os.MkdirAll(filepath.Join(repoRoot, "pkg", "genpb"), 0o755); err != nil {
		t.Fatalf("MkdirAll genpb: %v", err)
	}
	if err := os.MkdirAll(filepath.Join(repoRoot, "pkg", "manual"), 0o755); err != nil {
		t.Fatalf("MkdirAll manual: %v", err)
	}
	if err := os.MkdirAll(filepath.Join(repoRoot, "pkg", "autogen"), 0o755); err != nil {
		t.Fatalf("MkdirAll autogen: %v", err)
	}
	if err := os.WriteFile(filepath.Join(repoRoot, "pkg", "genpb", "types.pb.go"), []byte("package genpb\n"), 0o644); err != nil {
		t.Fatalf("WriteFile pb.go: %v", err)
	}
	if err := os.WriteFile(filepath.Join(repoRoot, "pkg", "manual", "logic.go"), []byte("package manual\nfunc Run() {}\n"), 0o644); err != nil {
		t.Fatalf("WriteFile logic.go: %v", err)
	}
	if err := os.WriteFile(filepath.Join(repoRoot, "pkg", "autogen", "glue.go"), []byte("// Code generated by tool. DO NOT EDIT.\npackage autogen\n"), 0o644); err != nil {
		t.Fatalf("WriteFile glue.go: %v", err)
	}

	modulePath, err := ReadGoModulePath(repoRoot)
	if err != nil {
		t.Fatalf("ReadGoModulePath() error = %v", err)
	}
	if modulePath != "example.com/project" {
		t.Fatalf("ReadGoModulePath() = %q, want example.com/project", modulePath)
	}

	raw := []byte(strings.Join([]string{
		"mode: set",
		"example.com/project/pkg/genpb/types.pb.go:10.1,12.2 1 1",
		"example.com/project/pkg/manual/logic.go:3.1,3.10 1 1",
		"example.com/project/pkg/autogen/glue.go:2.1,2.10 1 1",
	}, "\n") + "\n")

	filtered, excluded, err := FilterHandwrittenGoCoverProfile(repoRoot, raw)
	if err != nil {
		t.Fatalf("FilterHandwrittenGoCoverProfile() error = %v", err)
	}
	filteredText := string(filtered)
	if strings.Contains(filteredText, "types.pb.go") || strings.Contains(filteredText, "glue.go") {
		t.Fatalf("filtered profile still contains generated file entries: %s", filteredText)
	}
	if !strings.Contains(filteredText, "pkg/manual/logic.go") {
		t.Fatalf("filtered profile dropped handwritten file: %s", filteredText)
	}
	if got := strings.Join(excluded, ","); got != "pkg/autogen/glue.go,pkg/genpb/types.pb.go" {
		t.Fatalf("excluded files = %q", got)
	}
}

func TestReadGoModulePathErrorsAndFallback(t *testing.T) {
	t.Run("falls back to cwd when repoRoot empty", func(t *testing.T) {
		originalWD, err := os.Getwd()
		if err != nil {
			t.Fatalf("os.Getwd: %v", err)
		}

		repoRoot := t.TempDir()
		if err := os.WriteFile(filepath.Join(repoRoot, "go.mod"), []byte("module example.com/fromcwd\n"), 0o644); err != nil {
			t.Fatalf("WriteFile go.mod: %v", err)
		}
		if err := os.Chdir(repoRoot); err != nil {
			t.Fatalf("Chdir repoRoot: %v", err)
		}
		t.Cleanup(func() { _ = os.Chdir(originalWD) })

		modulePath, err := ReadGoModulePath("")
		if err != nil {
			t.Fatalf("ReadGoModulePath(empty repoRoot) error = %v", err)
		}
		if modulePath != "example.com/fromcwd" {
			t.Fatalf("ReadGoModulePath(empty repoRoot) = %q, want example.com/fromcwd", modulePath)
		}
	})

	t.Run("rejects missing module directive", func(t *testing.T) {
		repoRoot := t.TempDir()
		if err := os.WriteFile(filepath.Join(repoRoot, "go.mod"), []byte("go 1.23\n"), 0o644); err != nil {
			t.Fatalf("WriteFile go.mod: %v", err)
		}
		if _, err := ReadGoModulePath(repoRoot); err == nil || !strings.Contains(err.Error(), "module directive not found") {
			t.Fatalf("expected missing module directive error, got %v", err)
		}
	})

	t.Run("blank module directive is rejected", func(t *testing.T) {
		repoRoot := t.TempDir()
		if err := os.WriteFile(filepath.Join(repoRoot, "go.mod"), []byte("module   \n"), 0o644); err != nil {
			t.Fatalf("WriteFile go.mod: %v", err)
		}
		if _, err := ReadGoModulePath(repoRoot); err == nil || !strings.Contains(err.Error(), "module directive not found") {
			t.Fatalf("expected blank module directive rejection, got %v", err)
		}
	})
}

func canonicalPath(t *testing.T, path string) string {
	t.Helper()
	resolved, err := filepath.EvalSymlinks(path)
	if err != nil {
		return filepath.Clean(path)
	}
	return filepath.Clean(resolved)
}

func TestFindRepoRootFromCwd(t *testing.T) {
	originalWD, err := os.Getwd()
	if err != nil {
		t.Fatalf("os.Getwd: %v", err)
	}
	t.Cleanup(func() { _ = os.Chdir(originalWD) })

	repoRoot := t.TempDir()
	nested := filepath.Join(repoRoot, "a", "b")
	if err := os.MkdirAll(nested, 0o755); err != nil {
		t.Fatalf("MkdirAll: %v", err)
	}
	if err := os.WriteFile(filepath.Join(repoRoot, "go.mod"), []byte("module example.com/test\n"), 0o644); err != nil {
		t.Fatalf("WriteFile go.mod: %v", err)
	}
	if err := os.Chdir(nested); err != nil {
		t.Fatalf("Chdir nested: %v", err)
	}
	if got := canonicalPath(t, FindRepoRootFromCwd()); got != canonicalPath(t, repoRoot) {
		t.Fatalf("FindRepoRootFromCwd() = %q, want %q", got, canonicalPath(t, repoRoot))
	}

	noRepo := t.TempDir()
	if err := os.Chdir(noRepo); err != nil {
		t.Fatalf("Chdir noRepo: %v", err)
	}
	if got := canonicalPath(t, FindRepoRootFromCwd()); got != canonicalPath(t, noRepo) {
		t.Fatalf("FindRepoRootFromCwd() without go.mod = %q, want %q", got, canonicalPath(t, noRepo))
	}
}

func TestWriteCoverageJSONAndSplitHelpers(t *testing.T) {
	repoRoot := t.TempDir()
	if err := WriteCoverageJSON(repoRoot, "portal", `{"ok":true}`); err != nil {
		t.Fatalf("WriteCoverageJSON: %v", err)
	}
	nycOutputDir, err := resolveCoverageNycOutputDir(repoRoot, "")
	if err != nil {
		t.Fatalf("resolveCoverageNycOutputDir: %v", err)
	}
	entries, err := os.ReadDir(nycOutputDir)
	if err != nil {
		t.Fatalf("ReadDir nyc_output: %v", err)
	}
	if len(entries) != 1 || !strings.HasPrefix(entries[0].Name(), "choysum-portal-") || !strings.HasSuffix(entries[0].Name(), ".json") {
		t.Fatalf("unexpected coverage files: %#v", entries)
	}

	content, err := os.ReadFile(filepath.Join(nycOutputDir, entries[0].Name()))
	if err != nil {
		t.Fatalf("ReadFile coverage json: %v", err)
	}
	if string(content) != `{"ok":true}` {
		t.Fatalf("coverage json = %q, want original payload", string(content))
	}

	if err := WriteCoverageJSON(repoRoot, "portal", "   "); err != nil {
		t.Fatalf("WriteCoverageJSON empty payload: %v", err)
	}

	globs := SplitCoverageGlobs(" src/**, foo/**;bar/**  baz/** ")
	if strings.Join(globs, ",") != "src/**,foo/**,bar/**,baz/**" {
		t.Fatalf("SplitCoverageGlobs() = %#v", globs)
	}
	reporters := SplitCoverageReporters("text; html")
	if strings.Join(reporters, ",") != "text,html" {
		t.Fatalf("SplitCoverageReporters() = %#v", reporters)
	}
}

