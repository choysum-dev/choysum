func TestGoCoverageHelperEdgeCases(t *testing.T) {
	t.Run("normalizeCoverageFilePath trims module and normalizes paths", func(t *testing.T) {
		if got := normalizeCoverageFilePath(" example.com/project/pkg/manual/logic.go ", "example.com/project"); got != "pkg/manual/logic.go" {
			t.Fatalf("normalizeCoverageFilePath(module-prefixed) = %q", got)
		}
		absPath := filepath.Join(t.TempDir(), "pkg", "logic.go")
		if got := normalizeCoverageFilePath(absPath, "example.com/project"); got != filepath.ToSlash(filepath.Clean(absPath)) {
			t.Fatalf("normalizeCoverageFilePath(abs) = %q, want %q", got, filepath.ToSlash(filepath.Clean(absPath)))
		}
	})

	t.Run("filters invalid coverprofiles", func(t *testing.T) {
		repoRoot := t.TempDir()
		if err := os.WriteFile(filepath.Join(repoRoot, "go.mod"), []byte("module example.com/project\n"), 0o644); err != nil {
			t.Fatalf("WriteFile go.mod: %v", err)
		}
		if _, _, err := FilterHandwrittenGoCoverProfile(repoRoot, []byte("not-a-coverprofile\n")); err == nil || !strings.Contains(err.Error(), "missing mode header") {
			t.Fatalf("expected missing mode header error, got %v", err)
		}
		badLine := []byte("mode: set\nexample.com/project/pkg/manual/logic.go 1 1\n")
		if _, _, err := FilterHandwrittenGoCoverProfile(repoRoot, badLine); err == nil || !strings.Contains(err.Error(), "invalid coverprofile line") {
			t.Fatalf("expected invalid coverprofile line error, got %v", err)
		}
	})

	t.Run("detects generated and handwritten files", func(t *testing.T) {
		repoRoot := t.TempDir()
		vendorDir := filepath.Join(repoRoot, "vendor", "pkg")
		genDir := filepath.Join(repoRoot, "pkg", "gen")
		manualDir := filepath.Join(repoRoot, "pkg", "manual")
		for _, dir := range []string{vendorDir, genDir, manualDir} {
			if err := os.MkdirAll(dir, 0o755); err != nil {
				t.Fatalf("MkdirAll %s: %v", dir, err)
			}
		}
		if err := os.WriteFile(filepath.Join(vendorDir, "manual.go"), []byte("package pkg\n"), 0o644); err != nil {
			t.Fatalf("WriteFile vendor manual.go: %v", err)
		}
		if err := os.WriteFile(filepath.Join(genDir, "glue.go"), []byte("// Code generated by tests. DO NOT EDIT.\npackage gen\n"), 0o644); err != nil {
			t.Fatalf("WriteFile generated glue.go: %v", err)
		}
		if err := os.WriteFile(filepath.Join(manualDir, "logic.go"), []byte("package manual\nfunc Run() {}\n"), 0o644); err != nil {
			t.Fatalf("WriteFile manual logic.go: %v", err)
		}

		if isGeneratedGoCoverageFile(repoRoot, "pkg/manual/readme.txt") {
			t.Fatal("expected non-go file to be ignored")
		}
		if isGeneratedGoCoverageFile(repoRoot, "vendor/pkg/manual.go") {
			t.Fatal("expected vendor handwritten go file not to be treated as generated")
		}
		if !isGeneratedGoCoverageFile(repoRoot, "pkg/gen/glue.go") {
			t.Fatal("expected generated marker file to be treated as generated")
		}
		if isGeneratedGoCoverageFile(repoRoot, "pkg/manual/logic.go") {
			t.Fatal("expected handwritten go file not to be treated as generated")
		}
		if isGeneratedGoCoverageFile(repoRoot, "pkg/manual/missing.go") {
			t.Fatal("expected missing go file to default to handwritten")
		}
	})

	t.Run("readFileHeader returns content and open errors", func(t *testing.T) {
		path := filepath.Join(t.TempDir(), "header.go")
		if err := os.WriteFile(path, []byte("package header\n// test content\n"), 0o644); err != nil {
			t.Fatalf("WriteFile header.go: %v", err)
		}
		header, err := readFileHeader(path, 7)
		if err != nil {
			t.Fatalf("readFileHeader(existing) error = %v", err)
		}
		if header != "package" {
			t.Fatalf("readFileHeader(existing) = %q, want package", header)
		}
		if _, err := readFileHeader(filepath.Join(t.TempDir(), "missing.go"), 32); err == nil {
			t.Fatal("expected readFileHeader to fail for missing file")
		}
	})
}
